//! `cargo xtask codegen [--check]` fixture tests: writing, and `--check` detecting stale
//! output, hand-edited output, missing output and orphan files. The fixtures configure the
//! adp target only, so no protoc is needed; the proto targets share the same output code.

use std::fs;
use std::path::PathBuf;

use codegen::{ErrorKind, Mode, Options, Report};

const OUT: &str = "contracts/adp/src/generated";
const FILE: &str = "contracts/adp/src/generated/droiduse.adp.rs";

const DEF: &str = r#"{
  "errors": [ { "name": "TIMEOUT", "description": "Timed out." } ],
  "envelope": { "types": [], "binary": "Framing." },
  "domains": [
    { "domain": "UI", "types": [
      { "id": "FrameId", "type": "object", "properties": [
        { "name": "display", "type": "integer", "format": "uint32" },
        { "name": "vsyncId", "type": "string", "format": "int64" }
      ] }
    ] }
  ]
}"#;

const CONFIG: &str = r#"
[adp]
definition = "contracts/adp/protocol.json"
version = "contracts/adp/VERSION"
out = "contracts/adp/src/generated"
"#;

struct Fx {
    _dir: tempfile::TempDir,
    root: PathBuf,
}

impl Fx {
    fn new() -> Fx {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().to_path_buf();
        let fx = Fx { _dir: dir, root };
        fx.write("build/codegen/codegen.toml", CONFIG);
        fx.write("contracts/adp/protocol.json", DEF);
        fx.write("contracts/adp/VERSION", "0.1.0\n");
        fx
    }

    fn write(&self, rel: &str, text: &str) {
        let p = self.root.join(rel);
        fs::create_dir_all(p.parent().unwrap()).unwrap();
        fs::write(p, text).unwrap();
    }

    fn read(&self, rel: &str) -> String {
        fs::read_to_string(self.root.join(rel)).unwrap()
    }

    fn path(&self, rel: &str) -> PathBuf {
        self.root.join(rel)
    }

    fn run(&self, mode: Mode) -> Report {
        codegen::run(&self.root, &Options { mode, only: None })
            .unwrap_or_else(|e| panic!("could not run: {e}"))
    }

    fn generate(&self) -> Report {
        self.run(Mode::Write)
    }

    fn check(&self) -> Report {
        self.run(Mode::Check)
    }

    fn err(&self, mode: Mode) -> codegen::Error {
        match codegen::run(&self.root, &Options { mode, only: None }) {
            Ok(r) => panic!("expected an error, got {r:?}"),
            Err(e) => e,
        }
    }
}

fn rules(r: &Report) -> Vec<&'static str> {
    let mut v: Vec<_> = r.violations.iter().map(|v| v.rule.id()).collect();
    v.sort();
    v
}

#[test]
fn generate_then_check_is_clean() {
    let fx = Fx::new();
    let r = fx.generate();
    assert_eq!(r.written, [FILE]);
    assert!(r.violations.is_empty());
    let r = fx.check();
    assert!(r.violations.is_empty(), "{r:?}");
    assert_eq!(r.files_checked, 1);
}

#[test]
fn regenerating_changes_nothing() {
    let fx = Fx::new();
    fx.generate();
    let before = fs::read(fx.path(FILE)).unwrap();
    let r = fx.generate();
    assert!(r.written.is_empty(), "{r:?}");
    assert_eq!(fs::read(fx.path(FILE)).unwrap(), before);
}

#[test]
fn output_is_byte_identical_across_roots() {
    // Two checkouts in different places produce the same bytes: no absolute paths,
    // timestamps or other run-dependent data.
    let a = Fx::new();
    let b = Fx::new();
    a.generate();
    b.generate();
    let ta = a.read(FILE);
    assert_eq!(ta, b.read(FILE));
    assert!(!ta.contains('\r'));
    for root in [&a.root, &b.root] {
        let s = root.display().to_string();
        assert!(!ta.contains(&s), "output contains the checkout path {s}");
    }
    assert!(ta.starts_with("// @generated by build/codegen"));
    assert!(ta.contains("contracts/adp/protocol.json"));
}

#[test]
fn check_does_not_write() {
    let fx = Fx::new();
    let r = fx.check();
    assert_eq!(rules(&r), ["codegen/missing"]);
    assert!(!fx.path(OUT).exists());
}

#[test]
fn stale_output_after_an_idl_change() {
    let fx = Fx::new();
    fx.generate();
    fx.write(
        "contracts/adp/protocol.json",
        &DEF.replace("\"display\"", "\"screen\""),
    );
    let r = fx.check();
    assert_eq!(rules(&r), ["codegen/stale"]);
    assert!(r.violations[0].to_string().contains(FILE));
    // regenerating fixes it
    fx.generate();
    assert!(fx.check().violations.is_empty());
}

