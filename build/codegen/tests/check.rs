#[test]
fn config_output_directory_must_be_a_contract_generated_dir() {
    for out in [
        "contracts/adp/src",
        "build/codegen/out",
        "/tmp/x",
        "contracts/adp/../node/src/generated",
        "contracts\\adp\\src\\generated",
    ] {
        let fx = Fx::new();
        fx.write(
            "build/codegen/codegen.toml",
            &CONFIG.replace(
                "out = \"contracts/adp/src/generated\"",
                &format!("out = {out:?}"),
            ),
        );
        assert_eq!(fx.err(Mode::Write).kind, ErrorKind::Config, "{out}");
    }
}

