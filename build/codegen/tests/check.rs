#[test]
fn only_selects_one_target() {
    let fx = Fx::new();
    let r = codegen::run(
        &fx.root,
        &Options {
            mode: Mode::Write,
            only: Some("adp".into()),
        },
    )
    .unwrap();
    assert_eq!(r.written, [FILE]);
    let e = codegen::run(
        &fx.root,
        &Options {
            mode: Mode::Check,
            only: Some("nope".into()),
        },
    )
    .unwrap_err();
    assert_eq!(e.kind, ErrorKind::Config);
}

#[test]
fn violation_lines_name_the_file_and_the_fix() {
    let fx = Fx::new();
    let r = fx.check();
    let line = r.violations[0].to_string();
    assert!(line.starts_with(FILE), "{line}");
    assert!(line.contains("cargo xtask codegen"), "{line}");
}
