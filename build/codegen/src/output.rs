//! Generated-file headers, and writing or checking the generated directories.

use std::collections::BTreeMap;
use std::fmt;
use std::fs;
use std::path::Path;

use sha2::{Digest, Sha256};

use crate::{Error, ErrorKind, Mode, Report};

const MARK: &str = "// @generated by build/codegen (`cargo xtask codegen`) from ";
const HASH: &str = "// body-sha256: ";

/// The files one target generates: repo-relative directory and file name → full text.
#[derive(Debug, Clone)]
pub struct GeneratedDir {
    pub dir: String,
    pub files: BTreeMap<String, String>,
}

/// Prefixes `body` with the generated-file header. `source` is repo-relative (no
/// absolute paths, nothing run-dependent).
pub fn file(source: &str, body: &str) -> String {
    let body = lf(body);
    format!(
        "{MARK}{source}. Do not edit.\n{HASH}{}\n{body}",
        hex(&Sha256::digest(body.as_bytes()))
    )
}

pub(crate) fn hex(b: &[u8]) -> String {
    b.iter().map(|b| format!("{b:02x}")).collect()
}

/// CRLF → LF (a Windows checkout with core.autocrlf).
pub(crate) fn lf(s: &str) -> String {
    s.replace("\r\n", "\n")
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Rule {
    /// An expected generated file does not exist.
    Missing,
    /// The file is generator output, but not for the current sources or settings.
    Stale,
    /// The file is not unmodified generator output.
    HandEdited,
    /// A file or empty directory in a generated directory that the generator does not produce.
    Orphan,
}

impl Rule {
    pub fn id(self) -> &'static str {
        match self {
            Rule::Missing => "codegen/missing",
            Rule::Stale => "codegen/stale",
            Rule::HandEdited => "codegen/hand-edited",
            Rule::Orphan => "codegen/orphan",
        }
    }
}

#[derive(Debug, Clone)]
pub struct Violation {
    /// Repo-relative path.
    pub path: String,
    pub rule: Rule,
    pub message: String,
}

impl fmt::Display for Violation {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}: {}: {}", self.path, self.rule.id(), self.message)
    }
}

fn violation(path: String, rule: Rule) -> Violation {
    let message = match rule {
        Rule::Missing => "generated file is missing; run `cargo xtask codegen`",
        Rule::Stale => "out of date with its sources or settings; run `cargo xtask codegen`",
        Rule::HandEdited => {
            "edited by hand (the body does not match its header hash); generated files are \
             not edited: change the source or the generator and run `cargo xtask codegen`"
        }
        Rule::Orphan => {
            "not produced by the generator; a generated directory holds generator output \
             only (`cargo xtask codegen` removes it)"
        }
    };
    Violation {
        path,
        rule,
        message: message.to_string(),
    }
}

/// Why `actual` (LF-normalized) differs from the generator output.
fn classify(actual: &str) -> Rule {
    let mut parts = actual.splitn(3, '\n');
    let (Some(mark), Some(hash), Some(body)) = (parts.next(), parts.next(), parts.next()) else {
        return Rule::HandEdited;
    };
    match (mark.starts_with(MARK), hash.strip_prefix(HASH)) {
        (true, Some(h)) if h == hex(&Sha256::digest(body.as_bytes())) => Rule::Stale,
        _ => Rule::HandEdited,
    }
}

fn io(what: &str, path: &Path, e: std::io::Error) -> Error {
    Error::new(
        ErrorKind::Io,
        format!("cannot {what} {}: {e}", path.display()),
    )
}

/// Writes (`Mode::Write`) or compares (`Mode::Check`) every generated directory.
pub fn apply(root: &Path, dirs: &[GeneratedDir], mode: Mode) -> Result<Report, Error> {
    let mut report = Report::default();
    for d in dirs {
        let abs = root.join(&d.dir);
        // Existing entries other than the expected files.
        if abs.is_dir() {
            walk_orphans(&abs, &d.dir, true, &d.files, mode, &mut report)?;
        }
        for (name, text) in &d.files {
            report.files_checked += 1;
            let rel = format!("{}/{name}", d.dir);
            let path = abs.join(name);
            let actual = match fs::symlink_metadata(&path) {
                Ok(m) if m.is_file() => Some(
                    fs::read(&path)
                        .map(|b| lf(&String::from_utf8_lossy(&b)))
                        .map_err(|e| io("read", &path, e))?,
                ),
                Ok(_) => {
                    // a directory or symlink where a generated file belongs
                    return Err(Error::new(
                        ErrorKind::Io,
                        format!("{rel}: is not a regular file"),
                    ));
                }
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
                Err(e) => return Err(io("read", &path, e)),
            };
            if actual.as_deref() == Some(text.as_str()) {
                continue;
            }
            match mode {
                Mode::Check => {
                    let rule = actual.as_deref().map_or(Rule::Missing, classify);
                    report.violations.push(violation(rel, rule));
                }
                Mode::Write => {
                    fs::create_dir_all(&abs).map_err(|e| io("create", &abs, e))?;
                    fs::write(&path, text).map_err(|e| io("write", &path, e))?;
                    report.written.push(rel);
                }
            }
        }
    }
    Ok(report)
}

/// Visits `dir` in sorted order. Reports (check) or removes (write) every file that is not
/// an expected top-level file, and every directory left without files. Returns whether the
/// directory still holds a file afterwards.
fn walk_orphans(
    dir: &Path,
    rel: &str,
    top: bool,
    expected: &BTreeMap<String, String>,
    mode: Mode,
    report: &mut Report,
) -> Result<bool, Error> {
    let mut entries = Vec::new();
    for e in fs::read_dir(dir).map_err(|e| io("read", dir, e))? {
        let e = e.map_err(|e| io("read", dir, e))?;
        let name = e.file_name().to_string_lossy().into_owned();
        entries.push((name, e.path()));
    }
    entries.sort();
    let mut keeps_file = false;
    for (name, path) in entries {
        let child_rel = format!("{rel}/{name}");
        let meta = fs::symlink_metadata(&path).map_err(|e| io("read", &path, e))?;
        if meta.is_dir() {
            if walk_orphans(&path, &child_rel, false, expected, mode, report)? {
                keeps_file = true;
                continue;
            }
            match mode {
                Mode::Check => report.violations.push(violation(child_rel, Rule::Orphan)),
                Mode::Write => {
                    fs::remove_dir(&path).map_err(|e| io("remove", &path, e))?;
                    report.removed.push(child_rel);
                }
            }
        } else if top && meta.is_file() && expected.contains_key(&name) {
            keeps_file = true;
        } else {
            // any other file, or a symlink (never followed)
            match mode {
                Mode::Check => {
                    report.violations.push(violation(child_rel, Rule::Orphan));
                    keeps_file = true;
                }
                Mode::Write => {
                    fs::remove_file(&path).map_err(|e| io("remove", &path, e))?;
                    report.removed.push(child_rel);
                }
            }
        }
    }
    Ok(keeps_file)
}
